# ---------- ensure_trusted ----------

def _write(path, obj):
    path.write_text(json.dumps(obj), encoding="utf-8")


def test_ensure_trusted_adds_project_and_defaults(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    _write(cj, {"numStartups": 3})
    assert wrapper.ensure_trusted(cj, "/work/a") is True
    data = json.loads(cj.read_text("utf-8"))
    assert data["projects"]["/work/a"]["hasTrustDialogAccepted"] is True
    assert data["hasCompletedOnboarding"] is True
    assert data["theme"] == "dark"
    assert data["numStartups"] == 3  # foreign keys preserved


def test_ensure_trusted_keeps_existing_theme_and_other_projects(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    _write(cj, {"theme": "light", "projects": {"/other": {"allowedTools": ["x"]}}})
    assert wrapper.ensure_trusted(cj, "/work/a") is True
    data = json.loads(cj.read_text("utf-8"))
    assert data["theme"] == "light"
    assert data["projects"]["/other"] == {"allowedTools": ["x"]}
    assert data["projects"]["/work/a"]["hasTrustDialogAccepted"] is True


def test_ensure_trusted_already_trusted_no_rewrite(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    cj.write_text(json.dumps({
        "hasCompletedOnboarding": True, "theme": "dark",
        "projects": {"/work/a": {"hasTrustDialogAccepted": True}},
    }, indent=7), encoding="utf-8")  # odd indent: a rewrite would be visible
    before = cj.read_bytes()
    mtime = cj.stat().st_mtime_ns
    assert wrapper.ensure_trusted(cj, "/work/a") is False
    assert cj.read_bytes() == before
    assert cj.stat().st_mtime_ns == mtime


def test_ensure_trusted_trust_false_is_fixed(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    _write(cj, {"hasCompletedOnboarding": True, "theme": "dark",
                "projects": {"/w": {"hasTrustDialogAccepted": False}}})
    assert wrapper.ensure_trusted(cj, "/w") is True
    assert json.loads(cj.read_text("utf-8"))["projects"]["/w"]["hasTrustDialogAccepted"] is True


def test_ensure_trusted_broken_json_untouched(wrapper, tmp_path, capsys):
    cj = tmp_path / ".claude.json"
    cj.write_text("{not json", encoding="utf-8")
    assert wrapper.ensure_trusted(cj, "/w") is False
    assert cj.read_text("utf-8") == "{not json"
    assert not list(tmp_path.glob(".claude.json.tmp-*"))


def test_ensure_trusted_missing_file_not_created(wrapper, tmp_path):
    cj = tmp_path / "absent.json"
    assert wrapper.ensure_trusted(cj, "/w") is False
    assert not cj.exists()


def test_ensure_trusted_non_dict_root_untouched(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    cj.write_text("[1, 2, 3]", encoding="utf-8")
    assert wrapper.ensure_trusted(cj, "/w") is False
    assert cj.read_text("utf-8") == "[1, 2, 3]"


def test_ensure_trusted_non_dict_projects_untouched(wrapper, tmp_path):
    cj = tmp_path / ".claude.json"
    cj.write_text(json.dumps({"projects": ["junk"]}), encoding="utf-8")
    assert wrapper.ensure_trusted(cj, "/w") is False
    assert json.loads(cj.read_text("utf-8")) == {"projects": ["junk"]}


