"""Tests for guest-mode helpers of the claude-telegram-bot launcher and the
guest systemd template unit, both generated by install.py.

The launcher is rendered with render_wrapper() into a temp dir (HOME is the
pytest tmp_path, so nothing touches real state) and imported via importlib;
the module has no import-time side effects (main() runs only under __main__).
"""
import importlib.util
import json
import os
import re
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
INSTALL_PY = REPO / "install.py"


def _load_install():
    spec = importlib.util.spec_from_file_location("install_under_test", INSTALL_PY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


install = _load_install()


@pytest.fixture
def home(tmp_path):
    h = tmp_path / "home"
    h.mkdir()
    return h


@pytest.fixture
def wrapper(home, tmp_path):
    """The launcher as a module, rendered with HOME=<tmp home>."""
    src = install.render_wrapper(str(home), "/x")
    path = tmp_path / "launcher_under_test.py"
    path.write_text(src, encoding="utf-8")
    spec = importlib.util.spec_from_file_location("launcher_under_test", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


